DIRECTION_BY_KEY: dict[str, str] = {
    key: title for key, title, _ in DIRECTION_OPTIONS
}

DIRECTION_TITLES: dict[str, str] = {
    f"direction_{key}": title for key, title, _ in DIRECTION_OPTIONS
}

DIRECTION_NAMES = frozenset(DIRECTION_BY_KEY.values())

DIRECTION_EMOJI_BY_TITLE: dict[str, str] = {
    title: emoji for _, title, emoji in DIRECTION_OPTIONS
}


def get_direction_title_by_key(key: str) -> str | None:
    return DIRECTION_BY_KEY.get(str(key).strip())


def is_known_direction(direction: str | None) -> bool:
    return direction is not None and direction.strip() in DIRECTION_NAMES
